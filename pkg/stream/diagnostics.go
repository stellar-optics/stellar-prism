package stream

import (
	"context"
	"fmt"
	"sort"
	"time"

	"github.com/stellar-optics/stellar-xdr-lens/pkg/lens"
	protocol "github.com/stellar/go-stellar-sdk/protocols/rpc"
	"github.com/stellar/go-stellar-sdk/xdr"

	"github.com/stellar-optics/stellar-prism/pkg/rpc"
)

// DefaultDiagnosticPageLimit is the page size requested for diagnostic event streams.
const DefaultDiagnosticPageLimit = 100

// DiagnosticEventType is the type of a Soroban diagnostic event.
type DiagnosticEventType string

const (
	// DiagnosticEventTypeInvokeHostFunction is a Soroban host function invocation.
	DiagnosticEventTypeInvokeHostFunction DiagnosticEventType = "invoke_host_function"
	// DiagnosticEventTypeContractEvent is a contract event.
	DiagnosticEventTypeContractEvent DiagnosticEventType = "contract_event"
	// DiagnosticEventTypeDeployment is a contract deployment.
	DiagnosticEventTypeDeployment DiagnosticEventType = "deployment"
	// DiagnosticEventTypeInvocation is a Soroban invocation.
	DiagnosticEventTypeInvocation DiagnosticEventType = "invocation"
)

// DiagnosticEvent represents a Soroban contract diagnostic or simulation event.
type DiagnosticEvent struct {
	// EventType identifies the kind of diagnostic event.
	EventType DiagnosticEventType
	// ContractID is the contract that generated the event.
	ContractID string
	// TransactionHash is the hash of the transaction that generated the event.
	TransactionHash string
	// Ledger is the ledger in which the event occurred.
	Ledger uint32
	// Time is when the event occurred.
	Time time.Time
	// AuthorizedInstitutions are the accounts authorized to perform the operation.
	AuthorizedInstitutions []string
	// ReturnValue is the return value from the host function.
	ReturnValue *xdr.ScVal
	// Footprint is the read/write footprint of the operation.
	Footprint *Footprint
	// Instructions are the execution instructions.
	Instructions []string
	// Events are any sub-events generated by the operation.
	Events []*DiagnosticEvent
}

// Footprint represents the read/write footprint of a Soroban operation.
type Footprint struct {
	// ReadSet is the set of keys read during the operation.
	ReadSet []string
	// WriteSet is the set of keys written during the operation.
	WriteSet []string
}

// DiagnosticQuery describes which diagnostic events to stream.
type DiagnosticQuery struct {
	// ContractIDs restricts the stream to these contracts. At most
	// MaxContractIDs are allowed by the server.
	ContractIDs []string
	// StartLedger is where a fresh stream begins. Zero means start from the
	// server's newest ledger.
	StartLedger uint32
	// PageLimit is the page size to request.
	PageLimit uint
	// EventTypes filters by event type. Empty means all types.
	EventTypes []DiagnosticEventType
}

// DiagnosticSource streams Soroban contract diagnostics and simulation events from RPC.
type DiagnosticSource struct {
	client rpc.Client
	query  DiagnosticQuery
}

// NewDiagnosticSource returns a Source over the given RPC client.
func NewDiagnosticSource(client rpc.Client, q DiagnosticQuery) (*DiagnosticSource, error) {
	if q.PageLimit == 0 {
		q.PageLimit = DefaultDiagnosticPageLimit
	}
	return &DiagnosticSource{
		client: client,
		query:  q,
	}, nil
}

// Name implements Source.
func (s *DiagnosticSource) Name() string { return "diagnostics" }

// Rewind implements Rewinder, repositioning a fresh fetch at ledger.
func (s *DiagnosticSource) Rewind(ledger uint32) {
	s.query.StartLedger = ledger
}

// CursorLedger implements Source by parsing the RPC cursor format.
func (s *DiagnosticSource) CursorLedger(cursor string) (uint32, bool) {
	if cursor == "" {
		return 0, false
	}
	c, err := protocol.ParseCursor(cursor)
	if err != nil {
		return 0, false
	}
	return c.Ledger, true
}

// Fetch implements Source.
func (s *DiagnosticSource) Fetch(ctx context.Context, cursor string) (Batch, error) {
	req := protocol.GetEventsRequest{
		Filters: []protocol.EventFilter{
			{
				EventType: protocol.EventTypeSet{
					protocol.EventTypeDiagnostic: nil,
				},
			},
		},
		Pagination: &protocol.PaginationOptions{
			Limit: s.query.PageLimit,
		},
	}

	if cursor == "" {
		req.StartLedger = s.query.StartLedger
	} else {
		parsed, err := protocol.ParseCursor(cursor)
		if err != nil {
			return Batch{}, rpc.Permanent(fmt.Errorf("invalid cursor %q: %w", cursor, err))
		}
		req.Pagination.Cursor = &parsed
	}

	if len(s.query.ContractIDs) > 0 {
		req.Filters[0].ContractIDs = s.query.ContractIDs
	}

	resp, err := s.client.GetEvents(ctx, req)
	if err != nil {
		return Batch{}, err
	}

	batch := Batch{
		Records:    make([]Record, 0, len(resp.Events)),
		NextCursor: resp.Cursor,
		Latest:     resp.LatestLedger,
		Oldest:     resp.OldestLedger,
		Full:       uint(len(resp.Events)) >= s.query.PageLimit,
	}

	for _, e := range resp.Events {
		diagRecord := diagnosticEventFromRPC(e)
		if diagRecord != nil {
			batch.Records = append(batch.Records, *diagRecord)
		}
	}

	sort.Slice(batch.Records, func(i, j int) bool {
		return batch.Records[i].ID < batch.Records[j].ID
	})

	return batch, nil
}

// diagnosticEventFromRPC converts an RPC event info into a DiagnosticEvent record.
func diagnosticEventFromRPC(e protocol.EventInfo) *Record {
	var eventType DiagnosticEventType
	switch e.EventType {
	case string(DiagnosticEventTypeContractEvent), "contract":
		eventType = DiagnosticEventTypeContractEvent
	case string(DiagnosticEventTypeDeployment):
		eventType = DiagnosticEventTypeDeployment
	case string(DiagnosticEventTypeInvocation):
		eventType = DiagnosticEventTypeInvocation
	default:
		eventType = DiagnosticEventTypeInvokeHostFunction
	}

	var closed time.Time
	if e.LedgerClosedAt != "" {
		if parsed, err := time.Parse(time.RFC3339, e.LedgerClosedAt); err == nil {
			closed = parsed.UTC()
		}
	}

	var returnValue *xdr.ScVal
	if e.ValueXDR != "" {
		decoded, err := lens.DecodeAs(e.ValueXDR, "ScVal")
		if err == nil {
			if scv, ok := decoded.Raw.(*xdr.ScVal); ok {
				returnValue = scv
			}
		}
	}

	_ = &DiagnosticEvent{
		EventType:       eventType,
		ContractID:      e.ContractID,
		TransactionHash: e.TransactionHash,
		Ledger:          uint32(e.Ledger),
		Time:            closed,
		ReturnValue:     returnValue,
	}

	return &Record{
		ID:       e.ID,
		Sequence: uint32(e.Ledger),
		Time:     closed,
		Kind:     KindEvent,
		Event: &Event{
			Type:       e.EventType,
			ContractID: e.ContractID,
			TxHash:     e.TransactionHash,
			TxIndex:    e.TxIndex,
			OpIndex:    e.OpIndex,
			EventIndex: eventIndex(e.ID),
			TopicXDR:   e.TopicXDR,
			ValueXDR:   e.ValueXDR,
		},
	}
}
